"""
Builds the self-contained qq installers and uninstallers.

Each cluster configuration in `clusters/` is combined with `lib.sh` into
`qq-<cluster>-install.sh` and `qq-<cluster>-uninstall.sh`. The generic
configuration produces `qq-install.sh` and `qq-uninstall.sh`.
"""

import argparse
import re
from pathlib import Path
from typing import Literal

Action = Literal["install", "uninstall"]

SOURCE_DIR = Path(__file__).resolve().parent
CLUSTERS_DIR = SOURCE_DIR / "clusters"
LIBRARY = SOURCE_DIR / "lib.sh"
GENERIC = "generic"
VERSION_PATTERN = re.compile(r"[0-9][0-9A-Za-z.+-]*")


def script_name(cluster: str, action: Action) -> str:
    """
    Return the file name of the script for a cluster.

    Args:
        cluster: Name of the cluster configuration.
        action: Whether the script installs or uninstalls qq.

    Returns:
        File name of the script.
    """
    if cluster == GENERIC:
        return f"qq-{action}.sh"
    return f"qq-{cluster}-{action}.sh"


def _strip_leading_comments(text: str) -> str:
    """
    Remove the comment block at the start of a file, which describes the file itself.
    """
    lines = text.splitlines()
    while lines and (lines[0].startswith("#") or not lines[0].strip()):
        lines.pop(0)
    return "\n".join(lines).strip() + "\n"


def build_script(config: Path, action: Action, version: str) -> str:
    """
    Build the content of an installer or uninstaller.

    Args:
        config: Path to the cluster configuration.
        action: Whether the script installs or uninstalls qq.
        version: qq version to install, without the leading `v`.

    Returns:
        Content of the script.

    Raises:
        ValueError: If the version is not valid.
    """
    if not VERSION_PATTERN.fullmatch(version):
        raise ValueError(f"invalid qq version '{version}'")

    if action == "install":
        usage = "[--zsh] [--fish]"
        purpose = f"Installs qq {version}."
    else:
        usage = ""
        purpose = (
            f"Removes qq and all changes made by {script_name(config.stem, 'install')}."
        )

    header = (
        "#!/usr/bin/env bash\n"
        f"# {purpose}\n"
        f"# Usage: {script_name(config.stem, action)} {usage}".rstrip()
        + "\n#\n"
        "# This script is generated by scripts/installation/build.py. Do not edit it.\n"
        "\n"
        "set -euo pipefail\n"
        "\n"
        f'QQ_VERSION="{version}"\n'
        'USER="${USER:-$(id -un)}"\n'
    )

    parts = [
        header,
        config.read_text().strip() + "\n",
        _strip_leading_comments(LIBRARY.read_text()),
        f'qq_{action} "$@"\n',
    ]
    return "\n".join(parts)


def build_all(output_dir: Path, version: str) -> list[Path]:
    """
    Build installers and uninstallers for all clusters.

    Args:
        output_dir: Directory to write the scripts into. Created if missing.
        version: qq version to install, without the leading `v`.

    Returns:
        Paths to the written scripts.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for config in sorted(CLUSTERS_DIR.glob("*.sh")):
        for action in ("install", "uninstall"):
            path = output_dir / script_name(config.stem, action)
            path.write_text(build_script(config, action, version))
            path.chmod(0o755)
            written.append(path)
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the qq installation scripts.")
    parser.add_argument(
        "version", help="qq version to install, without the leading 'v'"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("dist/installation"),
        help="output directory (default: dist/installation)",
    )
    args = parser.parse_args()

    for path in build_all(args.output, args.version):
        print(path)


if __name__ == "__main__":
    main()
