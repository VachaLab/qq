class Panel:
    """
    A dark rounded panel. Text goes on a clipped layer (`d`) that fades out where it
    runs past the right padding; shapes behind the text go on the background (`bg`).
    """

    def __init__(self, img, box, radius=12, pad=16, color=TERM_BG):
        self.img, self.pad, self.radius = img, pad, radius
        x0, y0, x1, y1 = (round(v) for v in box)
        self.box = (x0, y0, x1, y1)
        self.canvas = Image.new("RGB", (max(1, x1 - x0), max(1, y1 - y0)), color)
        self.layer = Image.new("RGBA", self.canvas.size, (0, 0, 0, 0))
        self.bg = ImageDraw.Draw(self.canvas)
        self.d = ImageDraw.Draw(self.layer)

    def close(self, fade=34, alpha=1.0):
        w, h = self.canvas.size
        end = w - self.pad // 2
        if end > fade:
            a = self.layer.getchannel("A")
            ramp = Image.linear_gradient("L").rotate(90).resize((fade, h))
            ramp = Image.eval(ramp, lambda v: 255 - v)
            region = a.crop((end - fade, 0, end, h))
            a.paste(
                Image.composite(region, Image.new("L", region.size, 0), ramp),
                (end - fade, 0),
            )
            a.paste(0, (end, 0, w, h))
            self.layer.putalpha(a)
        self.canvas.paste(self.layer, (0, 0), self.layer)
        mask = rrect(w, h, self.radius, (255, 255, 255, 255)).getchannel("A")
        if alpha < 1:
            mask = mask.point(lambda v: round(v * alpha))
        self.img.paste(self.canvas, self.box[:2], mask)


