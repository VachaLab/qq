def render_frames():
    n = round(total_duration() * 1000 / FRAME_MS)
    frames, durations = [], []
    for i in range(n):
        img = frame(i * FRAME_MS / 1000)
        if frames and img.tobytes() == frames[-1].tobytes():
            durations[-1] += FRAME_MS
        else:
            frames.append(img)
            durations.append(FRAME_MS)
        if i % 100 == 0:
            print(f"  {i}/{n} frames")
    return frames, durations


def build_palette(frames):
    step = max(1, len(frames) // 90)
    sample = frames[::step]
    tile = W // 2
    sheet = Image.new("RGB", (tile, tile * len(sample)))
    for i, f in enumerate(sample):
        sheet.paste(f.resize((tile, tile), Image.NEAREST), (0, i * tile))
    return sheet.quantize(colors=128, method=Image.Quantize.MEDIANCUT, kmeans=2)


def main():
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("-o", "--output", default="qq_overview.gif")
    parser.add_argument(
        "--still", type=float, help="render one frame at this time to a PNG"
    )
    args = parser.parse_args()

    fetch_fonts()
    if args.still is not None:
        out = Path(args.output).with_suffix(".png")
        frame(args.still).save(out)
        print(f"wrote {out}")
        return

    print(f"rendering {total_duration():.1f} s at {1000 / FRAME_MS:.1f} fps")
    frames, durations = render_frames()
    palette = build_palette(frames)
    indexed = [f.quantize(palette=palette, dither=Image.Dither.NONE) for f in frames]
    indexed[0].save(
        args.output,
        save_all=True,
        append_images=indexed[1:],
        duration=durations,
        loop=0,
        optimize=False,
        disposal=1,
    )
    size = Path(args.output).stat().st_size / 1e6
    print(
        f"wrote {args.output}: {len(indexed)} frames, {total_duration():.1f} s, {size:.1f} MB"
    )


if __name__ == "__main__":
    main()
