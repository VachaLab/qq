@cache
def final_content(name):
    dur, fn = SCENES_BY_NAME[name]
    return fn(dur - 1e-3)


def frame(t):
    start = 0.0
    for k, (name, dur, fn) in enumerate(SCENES):
        if t < start + dur or k == len(SCENES) - 1:
            break
        start += dur
    lt = t - start
    img = fn(lt)
    if name in PUSH and lt < PUSH_LEN:
        prev = final_content(SCENES[k - 1][0])
        e = ease_io(lt / PUSH_LEN)
        out = Image.new("RGB", (W, H), BG)
        if PUSH[name] == "up":
            out.paste(prev, (0, round(-H * e)))
            out.paste(img, (0, round(H * (1 - e))))
        else:
            out.paste(prev, (round(-W * e), 0))
            out.paste(img, (round(W * (1 - e)), 0))
        img = out
    chrome(img, t)
    return img


def total_duration():
    return sum(dur for _, dur, _ in SCENES)


