def _gradient(size, a, b):
    small = Image.new("RGB", (64, 64))
    px = small.load()
    for y in range(64):
        for x in range(64):
            px[x, y] = mix(a, b, (x + y) / 126)
    return small.resize(size, Image.BILINEAR)


@cache
def q_glyph(height: int, teal: bool) -> Image.Image:
    """One letter of the logo, 316 x 422 logo units."""
    scale = height * SS / 422
    w, h = round(318 * scale), round(422 * scale)

    def s(v):
        return round(v * scale)

    mask = Image.new("L", (w, h), 0)
    md = ImageDraw.Draw(mask)
    md.ellipse([s(0.5), s(3), s(316.5), s(321)], fill=255)
    md.rectangle([s(248), s(162), s(315.5), s(400)], fill=255)
    md.rounded_rectangle([s(248), s(380), s(315.5), s(421.5)], radius=s(9), fill=255)
    md.ellipse([s(65), s(65), s(253), s(261)], fill=0)
    a, b = (TEAL_A, TEAL_B) if teal else (PURPLE_A, PURPLE_B)
    out = _gradient((w, h), a, b).convert("RGBA")
    out.putalpha(mask)
    return out.resize((max(1, round(w / SS)), height), Image.LANCZOS)


def draw_logo(img, x, y, height, offsets=((0, 0), (0, 0)), scale=1.0, alpha=1.0):
    """Draw the logo with its top-left corner at (x, y); offsets move each q."""
    h = max(2, round(height * scale))
    gap = 344 * h / 422
    for k, (dx, dy) in enumerate(offsets):
        paste(img, q_glyph(h, k == 1), x + k * gap + dx, y + dy, alpha)


