def _cycles():
    """Times per cycle: queued, running, script finished (archive), finished."""
    cycles, que, run = {}, 0.8, 1.3
    for k in range(1, 6):
        script_end = run + FILL_TIME
        end = script_end + 0.9
        cycles[k] = {"que": que, "run": run, "script_end": script_end, "end": end}
        que, run = script_end + 0.85, end + 0.45
    return cycles


