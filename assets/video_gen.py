def enter_time(cmd, start, cps=18.0):
    return start + 0.25 + len(cmd) / cps + 0.25


def command_bar(img, box, cmd, t, start, cps=18.0, alpha=1.0, glob=None):
    """
    A typed command without any terminal around it. Returns the time Enter is pressed.
    `glob` is a substring that gets a purple background once the command is entered.
    """
    enter = enter_time(cmd, start, cps)
    if alpha <= 0:
        return enter
    x0, y0, x1, y1 = box
    w, h = round(x1 - x0), round(y1 - y0)
    flash = math.sin(math.pi * prog(t, enter, 0.35))
    outline = mix(TERM_BG, PURPLE_A, flash)
    paste(img, rrect(w, h, 12, TERM_BG + (255,), outline + (255,), 2), x0, y0, alpha)
    d = ImageDraw.Draw(img)
    font = F("mono", 18)
    cw = font.getlength("M")
    ty = y0 + (h - 22) / 2
    tx = x0 + 22
    text(d, (tx, ty), "$", font, mix(TERM_BG, P_USER, alpha))
    tx += 2 * cw
    n = min(len(cmd), max(0, int((t - start - 0.25) * cps)))
    if glob and glob in cmd and t > enter:
        g = cmd.index(glob)
        a = ease_out(prog(t, enter + 0.1, 0.3)) * alpha
        gx = tx + g * cw
        paste(
            img,
            rrect(
                round(len(glob) * cw + 10), 30, 6, mix(TERM_BG, PURPLE, 0.75) + (255,)
            ),
            gx - 5,
            ty - 3,
            a,
        )
    text(d, (tx, ty), cmd[:n], font, mix(TERM_BG, WHITE, alpha))
    if t < enter and (n < len(cmd) or (t % 1.0) < 0.6):
        cx = tx + n * cw
        d.rectangle([cx, ty + 1, cx + cw - 2, ty + 22], fill=mix(TERM_BG, FG, alpha))
    return enter


