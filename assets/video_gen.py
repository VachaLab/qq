def bezier(p0, p1, lift, t):
    cx, cy = (p0[0] + p1[0]) / 2, min(p0[1], p1[1]) - lift
    x = (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * cx + t**2 * p1[0]
    y = (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * cy + t**2 * p1[1]
    return x, y


def fly(img, sprite, p0, p1, p, lift=80, trail=None):
    """Draw a sprite flying along an arc, with a short fading trail."""
    if p <= 0 or p >= 1:
        return
    if trail is not None:
        for k, a in ((2, 0.12), (1, 0.25)):
            q = p - k * 0.055
            if q > 0:
                x, y = bezier(p0, p1, lift, ease_io(q))
                paste_c(img, trail, x, y, 1.0, a)
    x, y = bezier(p0, p1, lift, ease_io(p))
    paste_c(img, sprite, x, y, 1 + 0.18 * math.sin(math.pi * p))


def ring(img, cx, cy, p, r0, r1, color, width=2):
    if not 0 < p < 1:
        return
    r = round(lerp(r0, r1, ease_out(p)))
    paste_c(
        img, rrect(2 * r, 2 * r, r, None, color + (255,), width), cx, cy, 1.0, 1 - p
    )


