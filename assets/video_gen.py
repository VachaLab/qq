SS = 4


@cache
def rrect(w, h, r, fill, outline=None, width=0):
    """A rounded rectangle sprite drawn at 4x and scaled down for smooth edges."""
    w, h = max(1, w), max(1, h)
    big = Image.new("RGBA", (w * SS, h * SS), (0, 0, 0, 0))
    ImageDraw.Draw(big).rounded_rectangle(
        [0, 0, w * SS - 1, h * SS - 1],
        radius=min(r, w // 2, h // 2) * SS,
        fill=fill,
        outline=outline,
        width=width * SS,
    )
    return big.resize((w, h), Image.LANCZOS)


def paste(img, sprite, x, y, alpha=1.0):
    if alpha <= 0:
        return
    if alpha < 1:
        sprite = sprite.copy()
        sprite.putalpha(sprite.getchannel("A").point(lambda v: round(v * alpha)))
    img.paste(sprite, (round(x), round(y)), sprite)


def scaled(sprite, s):
    if abs(s - 1) < 0.01:
        return sprite
    w, h = max(1, round(sprite.width * s)), max(1, round(sprite.height * s))
    return sprite.resize((w, h), Image.BILINEAR)


def paste_c(img, sprite, cx, cy, scale=1.0, alpha=1.0):
    sp = scaled(sprite, scale)
    paste(img, sp, cx - sp.width / 2, cy - sp.height / 2, alpha)


