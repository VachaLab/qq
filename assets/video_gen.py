def draw_cycle(img, box, k, state, fill, t, since, big=True):
    """Draw one cycle as a cell; `since` is when it entered its current state."""
    d = ImageDraw.Draw(img)
    x0, y0, x1, y1 = box
    w, h = round(x1 - x0), round(y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    num = F("sans-bold", 34 if big else 17)
    small = F("sans", 13)
    r = 12 if big else 7
    if state == "none":
        paste_c(img, rrect(w, h, r, BG + (255,), (214, 210, 226, 255), 2), cx, cy)
        text_c(d, cx, cy - (20 if big else 11), str(k), num, (206, 202, 220))
        return
    if state == "done":
        pop = 1 + 0.12 * math.sin(math.pi * prog(t, since, 0.35))
        paste_c(img, rrect(w, h, r, TEAL + (255,)), cx, cy, pop)
        text_c(d, cx, cy - (20 if big else 11), str(k), num, (255, 255, 255))
        if big:
            text_c(d, cx, y0 + 8, "cycle", small, (190, 228, 228))
        return
    color = STATE["queued"] if state == "queued" else PURPLE
    appear = ease_back(prog(t, since, 0.35)) if state == "queued" else 1.0
    cell = liquid_cell(w, h, color).copy()
    if state == "running":
        fh = round((h - 6) * clamp(fill))
        if fh > 0:
            liquid = rrect(
                w - 6, fh, max(1, r - 3), mix((255, 255, 255), PURPLE, 0.26) + (255,)
            )
            cell.paste(liquid, (3, h - 3 - fh), liquid)
            wave = ImageDraw.Draw(cell)
            for xx in range(3, w - 3, 2):
                yy = h - 3 - fh + 2 * math.sin(xx / 6 + t * 8)
                wave.line([xx, yy, xx + 2, yy], fill=mix((255, 255, 255), PURPLE, 0.5))
    paste_c(img, cell, cx, cy, max(0.05, appear))
    text_c(d, cx, cy - (20 if big else 11), str(k), num, color)
    if big:
        text_c(d, cx, y0 + 8, "cycle", small, mix((255, 255, 255), color, 0.7))


def aa_arrow(img, pts, color, width=3.0, head=10.0, alpha=1.0):
    """An anti-aliased polyline with round caps and an open chevron head at its end."""
    if len(pts) < 2 or alpha <= 0:
        return
    pad = head + width + 4
    x0 = min(x for x, _ in pts) - pad
    y0 = min(y for _, y in pts) - pad
    x1 = max(x for x, _ in pts) + pad
    y1 = max(y for _, y in pts) + pad
    w, h = round(x1 - x0), round(y1 - y0)
    layer = Image.new("RGBA", (w * SS, h * SS), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    rgba = color + (round(255 * alpha),)

    def sc(pt):
        return ((pt[0] - x0) * SS, (pt[1] - y0) * SS)

    lw = round(width * SS)
    r = lw / 2
    scaled_pts = [sc(pt) for pt in pts]
    d.line(scaled_pts, fill=rgba, width=lw, joint="curve")
    # direction of the last segment, from a point a little way back for stability
    tip = pts[-1]
    back = pts[max(0, len(pts) - 4)]
    ang = math.atan2(tip[1] - back[1], tip[0] - back[0])
    ends = [scaled_pts[0], scaled_pts[-1]]
    for side in (-1, 1):
        a = ang + math.pi + side * 0.55
        wing = (tip[0] + math.cos(a) * head, tip[1] + math.sin(a) * head)
        d.line([sc(tip), sc(wing)], fill=rgba, width=lw)
        ends.append(sc(wing))
    for ex, ey in ends:
        d.ellipse([ex - r, ey - r, ex + r, ey + r], fill=rgba)
    layer = layer.resize((w, h), Image.LANCZOS)
    img.paste(layer, (round(x0), round(y0)), layer)


def draw_resubmit_arrow(img, k, t, start, big=True, boxes=None):
    p = ease_io(prog(t, start, 0.45))
    if p <= 0:
        return
    a0, a1 = boxes(k), boxes(k + 1)  # ty:ignore[not-callable]
    p0 = ((a0[0] + a0[2]) / 2 + 10, a0[1] - 8)
    p1 = ((a1[0] + a1[2]) / 2 - 10, a1[1] - 8)
    heat = 1 - prog(t, start + 0.6, 0.8)
    color = mix((170, 164, 190), PURPLE, heat)
    lift = 38 if big else 14
    n = 32
    pts = [bezier(p0, p1, lift, i / n * p) for i in range(n + 1)]
    aa_arrow(img, pts, color, width=3.0 if big else 2.0, head=9.0 if big else 6.0)


