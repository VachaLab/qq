def scene_merge(t):
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)
    head = F("sans-bold", 22)
    a = prog(t, 0.15, 0.3) * (1 - prog(t, MERGE_LEN - 1.1, 0.4))
    text_c(d, LEFT_X, 134, "PBS Pro", head, mix(BG, TEAL, a))
    text_c(d, RIGHT_X, 134, "Slurm", head, mix(BG, TEAL, a))
    d.line([W / 2, 128, W / 2, 168], fill=mix(BG, CARD_LINE, a), width=2)

    more = ease_out(prog(t, MERGE_AT + len(PAIRS) * 0.36 + 0.6, 0.5)) * (
        1 - prog(t, MERGE_LEN - 0.9, 0.3)
    )
    if more > 0:
        text_c(
            d,
            W / 2,
            648 + 10 * (1 - more),
            MORE,
            F("sans-medium", 21),
            mix(BG, INK, more),
        )
    gather = ease_in(prog(t, MERGE_LEN - 0.7, 0.6))
    for i, (pbs, slurm, qq) in enumerate(PAIRS):
        start = 0.35 + i * 0.22
        meet = MERGE_AT + i * 0.36
        fused = meet + 0.3
        y = ROW_Y[i]
        slide = ease_out(prog(t, start, 0.45))
        if slide <= 0:
            continue
        converge = ease_in(prog(t, meet, fused - meet))
        if t < fused:
            lx = lerp(lerp(LEFT_X - 260, LEFT_X, slide), W / 2, converge)
            rx = lerp(lerp(RIGHT_X + 260, RIGHT_X, slide), W / 2, converge)
            alpha = slide * (1 - 0.5 * converge)
            paste_c(img, chip(pbs, "pbs"), lx, y, 1 - 0.25 * converge, alpha)
            paste_c(img, chip(slurm, "slurm"), rx, y, 1 - 0.25 * converge, alpha)
        else:
            ring(img, W / 2, y, prog(t, fused, 0.55), 30, 110, PURPLE)
            pop = ease_back(prog(t, fused, 0.45), 2.4)
            cy = lerp(y, BIG_LOGO_Y + BIG_LOGO_H / 2, gather)
            paste_c(
                img,
                chip(qq, "qq"),
                W / 2,
                cy,
                lerp(0.5, 1.0, pop) * (1 - 0.8 * gather),
                1 - gather,
            )
    return img


