def fetch_fonts() -> None:
    FONT_DIR.mkdir(exist_ok=True)
    for package, name, _ in FONT_FILES.values():
        target = FONT_DIR / name
        if target.exists():
            continue
        try:
            print(f"downloading {name}")
            urllib.request.urlretrieve(
                f"{PLEX}/{package}/fonts/complete/ttf/{name}", target
            )
        except Exception as e:
            print(f"could not download {name} ({e}); a fallback font will be used")
            target.unlink(missing_ok=True)


@cache
def F(kind: str, size: int) -> ImageFont.FreeTypeFont:
    _, name, fallback = FONT_FILES[kind]
    for candidate in (FONT_DIR / name, fallback):
        try:
            return ImageFont.truetype(str(candidate), size)
        except OSError:
            continue
    return ImageFont.load_default(size)


